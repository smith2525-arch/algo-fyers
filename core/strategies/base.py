"""Abstract strategy contract and immutable bar/position/signal value objects.

CRITICAL SAFETY INVARIANT:
Strategies inspect closed OHLCV bars and read-only position context, and emit
`SignalCandidate` objects ONLY. Strategies never create orders, fills, or
modify position ledgers.
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from collections.abc import Sequence
from dataclasses import dataclass, field
from datetime import datetime
from decimal import Decimal
from typing import TYPE_CHECKING, Any

from core.clock import ensure_ist
from core.domain.enums import ExitReason, Side, SignalDirection

if TYPE_CHECKING:
    from core.market_data.events import CandleEvent


@dataclass(frozen=True)
class OHLCVBar:
    """Immutable closed market candle normalized to Asia/Kolkata (IST, +05:30)."""

    symbol: str
    timeframe: str
    bar_timestamp: datetime
    open: Decimal
    high: Decimal
    low: Decimal
    close: Decimal
    volume: int = 0

    def __post_init__(self) -> None:
        object.__setattr__(self, "bar_timestamp", ensure_ist(self.bar_timestamp))


@dataclass(frozen=True)
class OpenPositionSnapshot:
    """Read-only view of an open position supplied to a strategy for exit signal evaluation."""

    symbol: str
    side: Side  # Side.BUY = long position, Side.SELL = short position
    entry_price: Decimal
    entry_bar_timestamp: datetime
    bars_held: int
    highest_price_since_entry: Decimal
    lowest_price_since_entry: Decimal

    def __post_init__(self) -> None:
        object.__setattr__(self, "entry_bar_timestamp", ensure_ist(self.entry_bar_timestamp))


@dataclass(frozen=True)
class SignalCandidate:
    """Immutable signal proposal generated by a strategy on bar close."""

    strategy_code: str
    symbol: str
    timeframe: str
    bar_timestamp: datetime
    side: Side
    direction: SignalDirection
    reference_price: Decimal
    rationale: str
    exit_reason: ExitReason | None = None
    indicators: dict[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        object.__setattr__(self, "bar_timestamp", ensure_ist(self.bar_timestamp))


class BaseStrategy(ABC):
    """Framework-agnostic interface implemented by all versioned trading strategies."""

    @property
    @abstractmethod
    def code(self) -> str:
        """Canonical strategy definition code."""

    @abstractmethod
    def evaluate_closed_bars(
        self,
        bars: Sequence[OHLCVBar],
        *,
        open_position: OpenPositionSnapshot | None = None,
        trades_taken_today: int = 0,
    ) -> SignalCandidate | None:
        """Evaluate historical closed bars up to `bars[-1]` and return an optional SignalCandidate."""

    def consume_candle_events(
        self,
        events: Sequence[CandleEvent],
        *,
        open_position: OpenPositionSnapshot | None = None,
        trades_taken_today: int = 0,
    ) -> SignalCandidate | None:
        """Evaluate normalized market `CandleEvent` stream without coupling to any feed source."""
        closed_bars = [ev.to_ohlcv_bar() for ev in events if ev.is_closed]
        if not closed_bars:
            return None
        return self.evaluate_closed_bars(
            closed_bars,
            open_position=open_position,
            trades_taken_today=trades_taken_today,
        )
